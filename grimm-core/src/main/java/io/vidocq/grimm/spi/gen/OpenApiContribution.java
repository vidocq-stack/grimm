package io.vidocq.grimm.spi.gen;

/**
 * Compile-time OpenAPI contribution of one JAX-RS resource class, implemented by
 * the {@code <Resource>$$GrimmModel} companion generated by the Grimm annotation
 * processor (codegen audit CG-06 — APT-first rule).
 *
 * <p>The contribution is the OpenAPI document fragment the runtime
 * {@code AnnotationScanner} would derive for this single class, serialized to
 * JSON at <em>compile time</em> by the processor (which builds the real model
 * objects inside javac and serializes them with grimm's own serializer). At
 * startup {@code ModelBuilder} parses the fragment and merges it additively with
 * the scan of the remaining classes — the reflective scan stays the documented
 * fallback for classes compiled without the processor or skipped by its
 * safety valve.</p>
 *
 * <p>Implementations must be stateless with a public no-arg constructor.</p>
 */
public interface OpenApiContribution {

    /** The JAX-RS resource class this fragment was derived from. */
    Class<?> resourceClass();

    /** The OpenAPI fragment (JSON, OpenAPI 3.1) for {@link #resourceClass()} only. */
    String openApiJson();
}
